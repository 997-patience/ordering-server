package com.wys.orderingserver;

import com.jayway.jsonpath.JsonPath;
import com.wys.orderingserver.utils.Md5Util;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.data.redis.core.StringRedisTemplate;
import org.springframework.data.redis.core.ValueOperations;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.TimeUnit;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

/** 用独立 H2 数据库补测管理员登录、退出、门店新增及顾客注册。 */
@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:interface-coverage;MODE=MySQL;DB_CLOSE_DELAY=-1",
        "spring.datasource.driver-class-name=org.h2.Driver", "spring.datasource.username=sa",
        "spring.datasource.password=", "spring.sql.init.mode=always",
        "spring.sql.init.schema-locations=classpath:store-page-test.sql,classpath:user-login-test.sql"
})
@AutoConfigureMockMvc
class InterfaceCoverageIntegrationTests {
    @Autowired private MockMvc mvc;
    @Autowired private JdbcTemplate jdbc;
    @MockitoBean private StringRedisTemplate redis;
    private final Map<String, String> tokens = new ConcurrentHashMap<>();

    @BeforeEach
    @SuppressWarnings("unchecked")
    void setup() {
        jdbc.execute("ALTER TABLE t_store ALTER COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100)");
        jdbc.update("UPDATE t_employee SET password=?, name=username, status=1", Md5Util.getMD5String("123456"));
        ValueOperations<String, String> ops = mock(ValueOperations.class);
        when(redis.opsForValue()).thenReturn(ops);
        when(ops.get(anyString())).thenAnswer(c -> tokens.get(c.getArgument(0)));
        doAnswer(c -> { tokens.put(c.getArgument(0), c.getArgument(1)); return null; })
                .when(ops).set(anyString(), anyString(), anyLong(), any(TimeUnit.class));
        when(redis.delete(anyString())).thenAnswer(c -> tokens.remove(c.getArgument(0)) != null);
    }

    private String adminLogin() throws Exception {
        String result = mvc.perform(post("/admin/login").contentType(MediaType.APPLICATION_JSON)
                .content("{\"username\":\"admin\",\"password\":\"123456\"}"))
                .andExpect(jsonPath("$.code").value(0)).andReturn().getResponse().getContentAsString();
        return JsonPath.read(result, "$.data");
    }

    @Test
    void loginInfoLogoutAndRevokedToken() throws Exception {
        String token = adminLogin();
        mvc.perform(get("/admin/info").header("Authorization", token))
                .andExpect(jsonPath("$.code").value(0)).andExpect(jsonPath("$.data.password").doesNotExist());
        mvc.perform(post("/admin/logout").header("Authorization", token)).andExpect(jsonPath("$.code").value(0));
        mvc.perform(get("/admin/info").header("Authorization", token)).andExpect(status().isUnauthorized());
    }

    @Test
    void superAdminCanCreateStoreWithGeneratedId() throws Exception {
        String token = adminLogin();
        mvc.perform(post("/admin/store").header("Authorization", token).contentType(MediaType.APPLICATION_JSON)
                .content("{\"name\":\"接口测试店\",\"status\":1}"))
                .andExpect(jsonPath("$.code").value(0));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM t_store WHERE name=? AND id IS NOT NULL", Integer.class, "接口测试店"));
    }

    @Test
    void storeNameIsRequired() throws Exception {
        String token = adminLogin();
        mvc.perform(post("/admin/store").header("Authorization", token).contentType(MediaType.APPLICATION_JSON)
                .content("{\"name\":\"   \",\"status\":1}"))
                .andExpect(jsonPath("$.code").value(1));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM t_store WHERE name='   '", Integer.class));
    }

    @Test
    void registerAndLoginCustomer() throws Exception {
        mvc.perform(post("/app/register").contentType(MediaType.APPLICATION_JSON)
                .content("{\"phone\":\"13800001234\",\"nickname\":\"test\",\"password\":\"123456\"}"))
                .andExpect(jsonPath("$.code").value(0));
        mvc.perform(post("/app/login").contentType(MediaType.APPLICATION_JSON)
                .content("{\"phone\":\"13800001234\",\"password\":\"123456\"}"))
                .andExpect(jsonPath("$.code").value(0)).andExpect(jsonPath("$.data").isString());
    }
}
